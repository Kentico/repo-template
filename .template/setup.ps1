<#
.SYNOPSIS
  One-time setup of a repository created from this template.

.DESCRIPTION
  Generic engine; templates built on top of this one do not edit this file but add data under
  .template/placeholders/*.json and scripts under .template/hooks/*.ps1.

  1. Reads every placeholders/*.json (name order). Each file maps a placeholder to a value that may use
     the tokens {ProjectName}, {ProjectNameDashed}, {ProjectShortName}, {ProjectShortNameLower},
     {RepositoryName}, {OwnerTeam}. Pairs with an empty value are skipped.
  2. Replaces the placeholders as plain strings in the text files of the repository, keeping line endings.
  3. Renames files whose names contain a placeholder.
  4. Runs hooks/*.ps1 (name order) with the resolved values; -HookOptions is handed to them as $Values.Options.
  5. Deletes the .template folder.

.PARAMETER ProjectName
  Required. Name of the main project and NuGet package, e.g. Kentico.Xperience.CoolProject.
.PARAMETER RepositoryName
  GitHub repository name. Default: derived from ProjectName
  (Kentico.Xperience.CoolProject -> xperience-by-kentico-cool-project).
.PARAMETER OwnerTeam
  GitHub team for CODEOWNERS, e.g. @Kentico/platform-engineering. Default: CODEOWNERS is left unchanged.
.PARAMETER HookOptions
  Hashtable handed to every hook as $Values.Options; see the hooks' own headers for the keys they read.

.EXAMPLE
  .\.template\setup.ps1 -ProjectName Kentico.Xperience.CoolProject -RepositoryName xperience-by-kentico-cool-project -OwnerTeam @Kentico/platform-engineering
  .\.template\setup.ps1 -ProjectName Kentico.Xperience.CoolProject -HookOptions @{ AdminUiExtension = $true }
#>
param (
    [Parameter(Mandatory)][string]$ProjectName,
    [string]$RepositoryName,
    [string]$OwnerTeam,
    [hashtable]$HookOptions = @{}
)

$ErrorActionPreference = 'Stop'
Set-Location "$PSScriptRoot\.."

$shortName = ($ProjectName -split '\.')[-1]
if (-not $RepositoryName) { $RepositoryName = 'xperience-by-kentico-' + ($shortName -creplace '(?<!^)([A-Z])', '-$1').ToLowerInvariant() }

$values = @{
    ProjectName           = $ProjectName
    ProjectNameDashed     = $ProjectName -replace '\.', '-'
    ProjectShortName      = $shortName
    ProjectShortNameLower = $shortName.ToLowerInvariant()
    RepositoryName        = $RepositoryName
    OwnerTeam             = $OwnerTeam
    Options               = $HookOptions
}

# 1. Placeholder pairs
$pairs = [ordered]@{}
foreach ($file in Get-ChildItem .template/placeholders/*.json | Sort-Object Name) {
    foreach ($pair in (Get-Content $file -Raw | ConvertFrom-Json).replace.PSObject.Properties) {
        $value = $pair.Value
        foreach ($token in 'ProjectName', 'ProjectNameDashed', 'ProjectShortName', 'ProjectShortNameLower', 'RepositoryName', 'OwnerTeam') {
            $value = $value.Replace("{$token}", [string]$values[$token])
        }
        if ($value) { $pairs[$pair.Name] = $value }
    }
}
Write-Host "Values:"
Write-Host "  ProjectName     $ProjectName"
Write-Host "  RepositoryName  $RepositoryName$(if (-not $PSBoundParameters.ContainsKey('RepositoryName')) { '   (derived)' })"
Write-Host "  OwnerTeam       $(if ($OwnerTeam) { $OwnerTeam } else { '(not set, CODEOWNERS unchanged)' })"
Write-Host "Placeholders:"
$pairs.GetEnumerator() | ForEach-Object { Write-Host ("  {0} -> {1}" -f $_.Key, $_.Value) }

# 2. Replace in text files, keeping line endings
$textFiles = Get-ChildItem -Recurse -File -Force |
    Where-Object { $_.FullName -notmatch '[\\/](\.git|\.template|bin|obj|node_modules)[\\/]' } |
    Where-Object { $_.Extension -in '.json', '.yml', '.yaml', '.props', '.targets', '.md', '.slnx', '.csproj', '.gitignore', '.editorconfig', '.gitattributes', '' }
foreach ($file in $textFiles) {
    $text = [IO.File]::ReadAllText($file.FullName)
    $new = $text
    foreach ($pair in $pairs.GetEnumerator()) { $new = $new.Replace($pair.Key, $pair.Value) }
    if ($new -ne $text) {
        [IO.File]::WriteAllText($file.FullName, $new)
        Write-Host "Replaced in $($file.FullName)"
    }
}

# 3. Rename files whose name contains a placeholder
foreach ($file in Get-ChildItem -Recurse -File | Where-Object { $_.FullName -notmatch '[\\/](\.git|\.template)[\\/]' }) {
    $newName = $file.Name
    foreach ($pair in $pairs.GetEnumerator()) { $newName = $newName.Replace($pair.Key, $pair.Value) }
    if ($newName -ne $file.Name) {
        Rename-Item -LiteralPath $file.FullName -NewName $newName
        Write-Host "Renamed $($file.Name) -> $newName"
    }
}

# 4. Hooks
foreach ($hook in Get-ChildItem .template/hooks/*.ps1 -ErrorAction Ignore | Sort-Object Name) {
    Write-Host "=== Hook $($hook.Name)"
    & $hook.FullName -Values $values
    if (-not $?) { throw "Hook $($hook.Name) failed." }
}

# 5. Clean up
Remove-Item .template -Recurse -Force
Write-Host "Setup complete."
