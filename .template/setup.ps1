<#
.SYNOPSIS
  One-time setup of a repository created from this template.

.DESCRIPTION
  Generic engine, owned by Platform Engineering. Templates built on top of this one do not edit this file;
  they add data under .template/placeholders/*.json and scripts under .template/hooks/*.ps1.

  1. Reads every placeholders/*.json (name order). Each file maps a placeholder to a value that may use
     the tokens {ProjectName}, {ProjectNameDashed}, {ProjectShortName}, {RepositoryName}, {OwnerTeam}.
  2. Replaces the placeholders as plain strings in every tracked text file, keeping line endings and BOM.
  3. Renames files and folders whose names contain a placeholder.
  4. Runs hooks/*.ps1 (name order) with the resolved values.
  5. Stops on the first error.
  6. Deletes the .template folder.

.EXAMPLE
  .\.template\setup.ps1 -ProjectName Kentico.Xperience.CoolProject -RepositoryName xperience-by-kentico-cool-project -OwnerTeam @Kentico/cool-team
#>
[CmdletBinding()]
param (
    [Parameter(Mandatory)][string]$ProjectName,
    [string]$RepositoryName,
    [string]$OwnerTeam,
    [switch]$AdminUiExtension,
    [switch]$KeepTemplateFolder
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$templateDir = $PSScriptRoot
$repoRoot = (Resolve-Path (Join-Path $templateDir '..')).Path
Set-Location $repoRoot

if ((git -C $repoRoot remote get-url origin 2>$null) -match 'Kentico/repo-template') {
    throw "This looks like a template repository itself. Run the setup only in a repository created from the template."
}

$shortName = ($ProjectName -split '\.')[-1]
if (-not $RepositoryName) { $RepositoryName = "xperience-by-kentico-" + ($shortName -creplace '(?<!^)([A-Z])', '-$1').ToLowerInvariant() }

$values = [ordered]@{
    ProjectName       = $ProjectName
    ProjectNameDashed = $ProjectName -replace '\.', '-'
    ProjectShortName  = $shortName
    ProjectShortNameLower = $shortName.ToLowerInvariant()
    RepositoryName    = $RepositoryName
    OwnerTeam         = $OwnerTeam
    AdminUiExtension  = [bool]$AdminUiExtension
}

function Expand-Tokens([string]$text) {
    foreach ($k in $values.Keys) { $text = $text.Replace("{$k}", [string]$values[$k]) }
    return $text
}

# 1. Collect placeholder pairs
$pairs = [ordered]@{}
Get-ChildItem (Join-Path $templateDir 'placeholders') -Filter *.json | Sort-Object Name | ForEach-Object {
    $json = Get-Content $_.FullName -Raw | ConvertFrom-Json
    foreach ($p in $json.replace.PSObject.Properties) {
        $value = Expand-Tokens $p.Value
        if ($value -match '\{\w+\}' -or [string]::IsNullOrEmpty($value)) {
            Write-Host "Skipping '$($p.Name)' - no value for it (file $($_.Name))."
            continue
        }
        $pairs[$p.Name] = $value
    }
}
Write-Host "Placeholders:"; $pairs.GetEnumerator() | ForEach-Object { Write-Host ("  {0} -> {1}" -f $_.Key, $_.Value) }

# 2. Replace in tracked text files (never inside .template)
$files = (git -C $repoRoot ls-files) | Where-Object { $_ -and -not $_.StartsWith('.template/') }
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
$utf8Bom = [System.Text.UTF8Encoding]::new($true)
foreach ($rel in $files) {
    $path = Join-Path $repoRoot $rel
    if (-not (Test-Path $path -PathType Leaf)) { continue }
    $bytes = [System.IO.File]::ReadAllBytes($path)
    if ($bytes.Length -eq 0) { continue }
    $probe = [Math]::Min($bytes.Length, 8000)
    if ([Array]::IndexOf($bytes[0..($probe - 1)], [byte]0) -ge 0) { continue } # binary
    $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
    $text = $utf8NoBom.GetString($bytes, ($hasBom ? 3 : 0), $bytes.Length - ($hasBom ? 3 : 0))
    $new = $text
    foreach ($kv in $pairs.GetEnumerator()) { $new = $new.Replace($kv.Key, $kv.Value) }
    if ($new -ne $text) {
        [System.IO.File]::WriteAllText($path, $new, ($hasBom ? $utf8Bom : $utf8NoBom))
        Write-Host "Replaced in $rel"
    }
}

# 3. Rename files and folders whose names contain a placeholder (deepest first)
$paths = $files | ForEach-Object { $_ } | Sort-Object { ($_ -split '/').Count } -Descending
$renamed = @{}
foreach ($rel in $paths) {
    $segments = $rel -split '/'
    for ($i = $segments.Count - 1; $i -ge 0; $i--) {
        $seg = $segments[$i]
        $newSeg = $seg
        foreach ($kv in $pairs.GetEnumerator()) { $newSeg = $newSeg.Replace($kv.Key, $kv.Value) }
        if ($newSeg -eq $seg) { continue }
        $oldPath = Join-Path $repoRoot (($segments[0..$i]) -join '/')
        if ($renamed.ContainsKey($oldPath) -or -not (Test-Path $oldPath)) { continue }
        $newPath = Join-Path (Split-Path $oldPath -Parent) $newSeg
        Move-Item -LiteralPath $oldPath -Destination $newPath
        $renamed[$oldPath] = $true
        Write-Host "Renamed $oldPath -> $newSeg"
    }
}

# 4. Hooks
$hooksDir = Join-Path $templateDir 'hooks'
if (Test-Path $hooksDir) {
    Get-ChildItem $hooksDir -Filter *.ps1 | Sort-Object Name | ForEach-Object {
        Write-Host "=== Hook $($_.Name)"
        & $_.FullName -Values $values
        if (-not $?) { throw "Hook $($_.Name) failed." }
    }
}

# 6. Clean up
if (-not $KeepTemplateFolder) {
    Remove-Item -LiteralPath $templateDir -Recurse -Force
    Write-Host "Removed .template"
}
Write-Host "Setup complete."
